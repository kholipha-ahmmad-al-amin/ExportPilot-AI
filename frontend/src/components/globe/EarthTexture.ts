export function createEarthTexture(oceanColor: string, landColor: string, borderSubtle: string): THREE.CanvasTexture {
  const W = 1024;
  const H = 512;
  const canvas = document.createElement('canvas');
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext('2d')!;

  // Ocean
  ctx.fillStyle = oceanColor;
  ctx.fillRect(0, 0, W, H);

  // Draw continents
  const toX = (lon: number): number => ((lon + 180) / 360) * W;
  const toY = (lat: number): number => ((90 - lat) / 180) * H;

  ctx.fillStyle = landColor;
  ctx.strokeStyle = borderSubtle;
  ctx.lineWidth = 1;

  for (const polygon of CONTINENTS) {
    ctx.beginPath();
    polygon.forEach(([lon, lat], i) => {
      const x = toX(lon);
      const y = toY(lat);
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    });
    ctx.closePath();
    ctx.fill();
    ctx.stroke();
  }

  const texture = new THREE.CanvasTexture(canvas);
  texture.wrapS = THREE.RepeatWrapping;
  texture.wrapT = THREE.ClampToEdgeWrapping;
  return texture;
}
